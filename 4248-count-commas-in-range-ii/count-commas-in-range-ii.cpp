class Solution {
public:
    long long countCommas(long long n) {
        long long ans = 0;

        // 1000 to 999999
        if (n >= 1000) {
            ans += min(n, 999999LL) - 1000 + 1;
        }

        // 1000000 to 999999999
        if (n >= 1000000) {
            if (n <= 999999999) {
                ans += 2 * (n - 1000000 + 1);
            } else {
                ans += 2 * (999999999 - 1000000 + 1);
            }
        }

        // 1000000000 to 999999999999
        if (n >= 1000000000LL) {
            if (n <= 999999999999LL) {
                ans += 3 * (n - 1000000000LL + 1);
            } else {
                ans += 3 * (999999999999LL - 1000000000LL + 1);
            }
        }

        // 1000000000000 to 999999999999999
        if (n >= 1000000000000LL) {
            if (n <= 999999999999999LL) {
                ans += 4 * (n - 1000000000000LL + 1);
            } else {
                ans += 4 * (999999999999999LL - 1000000000000LL + 1);
            }
        }

        // 1000000000000000
        if (n >= 1000000000000000LL) {
            ans += 5 * (n - 1000000000000000LL + 1);
        }

        return ans;
    }
};